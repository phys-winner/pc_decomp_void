"""Compile every static and procedural shader shipped in the 2009 release.

Uses the game's Effects/static.xml, including its defines and all profiles
allowed by a '>profile' entry. Results use android/host/d3dx9.c's exact key
and join build/shadercache/results, which build_game_apk.py packages.
"""
import json
from pathlib import Path
import struct
import subprocess
from xml.etree import ElementTree as ET

from shader_service import ROOT, WORK, build_tool


def hash64(data):
    key = 0xCBF29CE484222325
    for byte in data:
        key = ((key ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return key


def request(source, profile, macros=b"", flags=0):
    key = hash64(source + b"\0" + macros + b"main\0" + profile.encode() + b"\0" + struct.pack("<I", flags))
    header = (f"function=main\nprofile={profile}\nflags={flags}\ninclude=no\nmacros={len(macros)}\n".encode()
              + macros + f"source={len(source)}\n".encode())
    return f"{key:016x}", header + source


def shaders():
    # RendererD3D generates these before reading Effects/static.xml, even with an empty profile.
    source = (b"struct VS_INPUT {\nfloat4 Position: POSITION;\n};\n\n"
              b"float4x4 FullTransform: register(c0);\n\n"
              b"float4 CalcPosition(const VS_INPUT inp) {\nreturn inp.Position;\n}\n\n"
              b"float4 main(VS_INPUT inp): POSITION {\n{\n}\nreturn mul(CalcPosition(inp), FullTransform);\n}\n")
    for profile in ("vs_2_0", "vs_3_0"):
        macros = f"profile_{profile}=1\nprofile_vs=1\n".encode()
        yield "startup/position/" + profile, *request(source, profile, macros, flags=0x8010)

    index = json.loads((ROOT / "research/vfs-index.json").read_text(encoding="utf-8"))
    entries = {entry["name"].lower(): (Path(index["source"]) / container["name"], entry)
               for container in index["containers"] for entry in container["entries"]}

    def read(name):
        path, entry = entries[name.lower()]
        with path.open("rb") as handle:
            handle.seek(entry["offset"])
            source = handle.read(entry["size"])
        assert len(source) == entry["size"], name
        return source

    for stage in ET.fromstring(read("Effects\\static.xml")):
        for shader in stage:
            source = read("Effects\\" + shader.attrib["Filename"])
            profile = shader.attrib["Profile"]
            profiles = [profile]
            if profile.startswith(">"):
                minimum = profile[1:]
                supported = ["ps_2_0", "ps_2_a", "ps_2_b", "ps_3_0"] if stage.tag == "Pixel" else ["vs_1_1", "vs_2_0", "vs_3_0"]
                profiles = supported[supported.index(minimum):]
            macros = b""
            for define in filter(None, shader.get("Defines", "").split(";")):
                name, _, value = define.partition("=")
                macros += f"{name}={value}\n".encode()
            for profile in profiles:
                yield "static/" + shader.tag + "/" + profile, *request(source, profile, macros)

    for name in sorted(entries):
        if not name.endswith(".prc"):
            continue
        source = read(name)
        if not source.startswith(b"DDS "):
            yield name, *request(source, "tx_1_0")


def main():
    requests = WORK / "all-requests"
    results = WORK / "results"
    requests.mkdir(parents=True, exist_ok=True)
    results.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name, key, data in shaders():
        (requests / (key + ".req")).write_bytes(data)
        manifest[name] = key
    completed = subprocess.run([str(build_tool()), str(requests), str(results)],
                               capture_output=True, text=True, check=True)
    absent = [key for key in manifest.values() if not (results / (key + ".bin")).is_file()]
    if absent:
        raise SystemExit(completed.stdout + completed.stderr + f"\nMissing bytecode: {absent}")
    (WORK / "all-static.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    obscura = sorted({hash64((results / (key + ".bin")).read_bytes()) for name, key in manifest.items()
                      if name.startswith("static/CompositeObscure")})
    (ROOT / "android/host/hud_shaders.h").write_text(
        "/* Generated by tools/build_shader_cache.py: the Sisters' obscura compositors. */\n"
        "static const uint64_t obscura_shaders[] = {\n"
        + "".join(f"    UINT64_C(0x{key:016X}),\n" for key in obscura) + "};\n", encoding="ascii")
    print(f"Compiled {len(manifest)} static/procedural variants ({len(set(manifest.values()))} unique); no failures")


if __name__ == "__main__":
    main()
