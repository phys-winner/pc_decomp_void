"""Lift a real Engine.dll routine and generate an independent x86 oracle."""
import hashlib
import json
from pathlib import Path
import random
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
DEPENDENCY = ROOT / "reference/pcrecomp"
sys.path.insert(0, str(DEPENDENCY))
from tools.pe.pe_analyze import analyze_pe
from tools.disasm.disasm32 import Disassembler
from tools.lift import lift32_cpu
from unicorn import Uc, UC_ARCH_X86, UC_MODE_32
from unicorn.x86_const import (
    UC_X86_REG_EAX, UC_X86_REG_ECX, UC_X86_REG_EDX, UC_X86_REG_EBX,
    UC_X86_REG_ESP, UC_X86_REG_EBP, UC_X86_REG_ESI, UC_X86_REG_EDI,
    UC_X86_REG_EFLAGS, UC_X86_REG_EIP,
)

STACK = 0x20000000
STACK_SIZE = 0x10000
RETURN = 0x30000000
REGISTERS = [UC_X86_REG_EAX, UC_X86_REG_ECX, UC_X86_REG_EDX, UC_X86_REG_EBX,
             UC_X86_REG_ESP, UC_X86_REG_EBP, UC_X86_REG_ESI, UC_X86_REG_EDI]
INITIAL = [0, 0x12345678, 0x87654321, 0x13579BDF,
           STACK + STACK_SIZE - 4, 0x2468ACE0, 0x55AA55AA, 0xAA55AA55]
FLAGS_MASK = 0x8D5  # CF, PF, AF, ZF, SF, OF, defined by the final CMP.


def main():
    dependency = json.loads((ROOT / "dependencies.json").read_text())["pcrecomp"]
    revision = subprocess.check_output(
        ["git", "-C", str(DEPENDENCY), "rev-parse", "HEAD"], text=True).strip()
    if revision != dependency["revision"]:
        raise ValueError("pcrecomp revision differs from dependencies.json")
    config = json.loads((ROOT / "port.json").read_text())
    probe = config["probe"]
    binary = Path(config["game_directory"]) / "bin/win32" / probe["module"]
    raw = binary.read_bytes()
    if hashlib.sha256(raw).hexdigest() != probe["sha256"]:
        raise ValueError("Engine.dll hash changed; addresses must be revalidated")
    info = analyze_pe(str(binary))
    reader = Disassembler(raw, info.image_base, info.sections)
    address = probe["va"]
    code = reader.read_bytes(address, probe["size"])
    if code is None or len(code) != probe["size"]:
        raise ValueError("Probe is outside the PE's file-backed sections")
    lift32_cpu.IMAGE_BASE = info.image_base
    lifter = lift32_cpu.Lifter(str(binary), info.code_end - info.image_base,
                               reader.read_bytes)
    instructions = list(lifter.md.disasm(code, address))
    if sum(i.size for i in instructions) != len(code):
        raise ValueError("Incomplete instruction decoding")
    lifted = lifter.lift_function(code, address)
    if "RECOMP_TODO" in lifted or "dispatch(" in lifted or "dispatch_jmp(" in lifted:
        raise ValueError("Probe contains unsupported instructions or external calls")

    rng = random.Random(0x4668E7B)
    numbers = {1, 0xFFFFFFFF}
    for bit in range(32):
        for n in ((1 << bit) - 1, 1 << bit, (1 << bit) + 1):
            if 0 < n <= 0xFFFFFFFF:
                numbers.add(n)
    numbers.update(rng.randrange(1, 1 << 32) for _ in range(2048))
    machine = Uc(UC_ARCH_X86, UC_MODE_32)
    page = address & ~0xFFF
    machine.mem_map(page, 0x1000)
    machine.mem_write(address, code)
    machine.mem_map(STACK, STACK_SIZE)
    machine.mem_map(RETURN, 0x1000)
    vectors = []
    clean_stack = bytearray([0xA5]) * STACK_SIZE
    clean_stack[-4:] = RETURN.to_bytes(4, "little")
    for n in sorted(numbers):
        machine.mem_write(STACK, bytes(clean_stack))
        for register, value in zip(REGISTERS, [n] + INITIAL[1:]):
            machine.reg_write(register, value)
        machine.reg_write(UC_X86_REG_EFLAGS, 2)
        machine.emu_start(address, RETURN, count=2048)
        final = [machine.reg_read(r) for r in REGISTERS]
        if machine.reg_read(UC_X86_REG_EIP) != RETURN:
            raise ValueError(f"Original did not return for {n:#x}")
        assert final[0] == n.bit_length() - 1
        assert final[3] == INITIAL[3] and final[5:] == INITIAL[5:]
        assert final[4] == STACK + STACK_SIZE
        vectors.append([n, final[0], final[1], final[2],
                        machine.reg_read(UC_X86_REG_EFLAGS) & FLAGS_MASK])
    # Detect future changes to the original's invalid-input behavior without hanging.
    machine.mem_write(STACK, bytes(clean_stack))
    for register, value in zip(REGISTERS, INITIAL):
        machine.reg_write(register, value)
    machine.emu_start(address, RETURN, count=2048)
    assert machine.reg_read(UC_X86_REG_EIP) != RETURN, "Zero-input contract changed"

    generated = ROOT / "generated/probe"
    generated.mkdir(parents=True, exist_ok=True)
    (generated / "lifted.c").write_text(
        '/* Generated from the verified Engine.dll; do not edit. */\n'
        '#include <stdlib.h>\n#include "cpu.h"\n' + lifted + "\n")
    rows = ",\n".join("    {" + ", ".join(f"0x{n:08X}u" for n in v) + "}"
                       for v in vectors)
    (generated / "vectors.h").write_text(
        "/* Generated by executing original x86 bytes in Unicorn. */\n"
        f"#define PROBE_ADDRESS 0x{address:08X}u\n"
        f"#define PROBE_FUNCTION L_{address:08X}\n"
        "static const unsigned char original_code[] = {" +
        ",".join(f"0x{b:02X}" for b in code) + "};\n"
        "typedef struct { uint32_t input, eax, ecx, edx, flags; } Vector;\n"
        "static const Vector vectors[] = {\n" + rows + "\n};\n")
    report = {"module": probe["module"], "sha256": probe["sha256"],
              "address": hex(address), "bytes": len(code),
              "instructions": len(instructions), "cases": len(vectors),
              "oracle": "Original x86 bytes in Unicorn; verified against bit_length",
              "native_x86": "PENDING", "native_arm64": "PENDING",
              "whole_game": "NOT ACHIEVED"}
    (generated / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
